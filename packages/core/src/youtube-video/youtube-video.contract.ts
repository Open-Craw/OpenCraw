/** What to read of a YouTube video besides what the page says about it. */
export interface YoutubeOptions {
  /** The language of the transcript to read, as the video's caption tracks name them (`en`, `pt-BR`); a base language (`pt`) matches a regional track. Default: the first track the uploader wrote, else the first automatic one. */
  language?:    string
  /** Translate the transcript to this language (`es`, `ja`…), as YouTube's own translation does; the track must allow it. */
  translateTo?: string
  /** Read the transcript; default true. `false` reads only what is about the video. */
  transcript?:  boolean
}

/** A caption track of a video. */
export interface CaptionTrack {
  /** The language code: `en`, `pt-BR`. */
  language:     string
  /** The track's name as YouTube shows it (`English`, `English (auto-generated)`). */
  name:         string
  /** Generated by speech recognition, not written by the uploader. */
  auto:         boolean
  /** Whether YouTube can translate it to other languages. */
  translatable: boolean
}

/** One line of a transcript: when it starts and how long it lasts, in seconds. */
export interface TranscriptSegment {
  start:    number
  duration: number
  text:     string
}

/** A transcript, in one language. */
export interface Transcript {
  /** The track's language, or the one it was translated to. */
  language:      string
  name:          string
  auto:          boolean
  /** The language it was translated to, when it was; `language` is then the same. */
  translatedTo?: string
  segments:      TranscriptSegment[]
  /** The lines joined by line breaks. */
  text:          string
}

/** A YouTube video as a document recipes read with JSONPath. */
export interface YoutubeVideo {
  videoId:       string
  url:           string
  title:         string
  author:        string
  channelId:     string
  description:   string
  lengthSeconds: number
  viewCount:     number
  keywords:      string[]
  isLive:        boolean
  publishDate?:  string
  category?:     string
  /** The largest thumbnail's address. */
  thumbnail?:    string
  /** The caption tracks the video has. */
  captions:      CaptionTrack[]
  /** The languages YouTube can translate a track to, when it says. */
  translations?: { language: string, name: string }[]
  /** The transcript, when there is a track and it was asked for. */
  transcript?:   Transcript
}

/** The two requests reading a video takes, made by whoever owns the network (the HTTP client, which checks hosts and carries a proxy). */
export interface YoutubeTransport {
  postJson: (url: string, headers: Record<string, string>, body: unknown) => Promise<{ status: number, json: unknown }>
  getText:  (url: string, headers: Record<string, string>) => Promise<{ status: number, text: string }>
}
